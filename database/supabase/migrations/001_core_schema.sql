create table if not exists public.academic_terms (
  id bigint generated by default as identity primary key,
  academic_year smallint not null check (academic_year > 0),
  term_code varchar(10) not null
    check (term_code in ('1', 'SUMMER', '2', 'WINTER')),
  display_name varchar(40) not null,
  starts_on date,
  ends_on date,
  created_at timestamptz not null default now(),
  constraint uq_academic_terms_year_code unique (academic_year, term_code),
  constraint chk_academic_terms_dates
    check (ends_on is null or starts_on is null or ends_on >= starts_on)
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  course_code varchar(32),
  course_name varchar(200) not null,
  department varchar(120),
  credits numeric(3, 1) check (credits is null or credits >= 0),
  course_type varchar(60),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ix_courses_code on public.courses (course_code);
create index if not exists ix_courses_name on public.courses (course_name);
create index if not exists ix_courses_department on public.courses (department);

create table if not exists public.course_sections (
  id bigint generated by default as identity primary key,
  term_id bigint not null references public.academic_terms (id) on delete restrict,
  course_id bigint not null references public.courses (id) on delete restrict,
  section_code varchar(20) not null,
  instructor_name varchar(120),
  room_summary varchar(200),
  capacity smallint check (capacity is null or capacity >= 0),
  enrolled_count smallint check (enrolled_count is null or enrolled_count >= 0),
  source_url varchar(2048),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_course_sections_term_course_section
    unique (term_id, course_id, section_code)
);

create index if not exists ix_course_sections_course_term
  on public.course_sections (course_id, term_id);
create index if not exists ix_course_sections_term_instructor
  on public.course_sections (term_id, instructor_name);

create table if not exists public.class_meetings (
  id bigint generated by default as identity primary key,
  course_section_id bigint not null
    references public.course_sections (id) on delete cascade,
  weekday smallint not null check (weekday between 1 and 7),
  starts_at time not null,
  ends_at time not null,
  room varchar(120),
  week_pattern varchar(20),
  constraint uq_meeting_slot
    unique (course_section_id, weekday, starts_at, ends_at),
  constraint chk_meetings_time check (ends_at > starts_at)
);

create index if not exists ix_meetings_weekday_time
  on public.class_meetings (weekday, starts_at, ends_at);

create table if not exists public.syllabi (
  id bigint generated by default as identity primary key,
  course_section_id bigint not null
    references public.course_sections (id) on delete cascade,
  source_url varchar(2048),
  file_storage_key varchar(1024),
  original_file_name varchar(255),
  content_text text,
  content_sha256 char(64)
    check (content_sha256 is null or content_sha256 ~ '^[0-9a-fA-F]{64}$'),
  parse_status varchar(20) not null default 'PENDING'
    check (parse_status in ('PENDING', 'SUCCESS', 'FAILED')),
  parse_error text,
  collected_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint uq_syllabi_section_hash
    unique (course_section_id, content_sha256)
);

create index if not exists ix_syllabi_parse_status
  on public.syllabi (parse_status);

create table if not exists public.timetables (
  id bigint generated by default as identity primary key,
  user_id varchar(128) not null,
  term_id bigint not null references public.academic_terms (id) on delete restrict,
  title varchar(100) not null default '내 시간표',
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists ix_timetables_user_term
  on public.timetables (user_id, term_id);

create table if not exists public.timetable_sections (
  timetable_id bigint not null
    references public.timetables (id) on delete cascade,
  course_section_id bigint not null
    references public.course_sections (id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (timetable_id, course_section_id)
);

create index if not exists ix_timetable_sections_section
  on public.timetable_sections (course_section_id);

create table if not exists public.personal_events (
  id bigint generated by default as identity primary key,
  user_id varchar(128) not null,
  title varchar(200) not null,
  description text,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  location varchar(200),
  color varchar(7) not null default '#4F46E5'
    check (color ~ '^#[0-9A-Fa-f]{6}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint chk_personal_events_time check (ends_at > starts_at)
