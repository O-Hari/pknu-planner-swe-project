drop policy if exists timetables_owner_access on public.timetables;
create policy timetables_owner_access on public.timetables
for all to authenticated
using (user_id = (select auth.uid())::text)
with check (user_id = (select auth.uid())::text);

drop policy if exists timetable_sections_owner_access on public.timetable_sections;
create policy timetable_sections_owner_access on public.timetable_sections
for all to authenticated
using (
  exists (
    select 1 from public.timetables t
    where t.id = timetable_id and t.user_id = (select auth.uid())::text
  )
)
with check (
  exists (
    select 1 from public.timetables t
    where t.id = timetable_id and t.user_id = (select auth.uid())::text
  )
);

drop policy if exists personal_events_owner_access on public.personal_events;
create policy personal_events_owner_access on public.personal_events
for all to authenticated
using (user_id = (select auth.uid())::text)
with check (user_id = (select auth.uid())::text);
